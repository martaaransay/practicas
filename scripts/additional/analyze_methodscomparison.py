# Import libraries 
import os
import glob
import pandas as pd

# Import functions from the pipeline module
from pipeline.blastn import process_blast_tsv
from pipeline.useful_funct import contig_to_genome, genome_key
from pipeline.analyze_Pc import extract_integron_info_gbk


#########################################################################
# To execute correctly this script, use this line for running:
# PYTHONPATH=scripts python scripts/additional/analyze_methodscomparison.py
#########################################################################


# CHANGE THE PARAMETERS BEFORE THE EXECUTION:

# To get folder names:

n = 250 # Number of genomes per species -> to specify the folder names
# min_length = ""
# min_length = "/700min_length"
min_length = "/1000min_length"

# min_length_tag = "min0_"
# min_length_tag = "min700_"
min_length_tag = "min1000_"

# Directory where genomes are saved
genomes_dir = f"../data_practicas/{n}genomes"
# Path to the blast tsv file
tsv = f"../results_practicas/{n}genomes/blast/blast_Int1_Pc_pattern.fa.tsv"
# Path to the csv file with IF2 info
if2_info = f"./results/plots/{n}genomes/results_files/integrons_info_IF2.csv"
# Path to the results csv file generated by methods_comparison script
csv = f"results/plots/{n}genomes/results_files/genomes_hits.csv"

# Output directory
out_dir = f"results/plots/{n}genomes{min_length}/discordant_genomes"

os.makedirs(out_dir, exist_ok=True) # to avoid errors

#### -------1) genomes with different number of hits in BLAST and IF2

# Read the results csv file as a pandas df
df = pd.read_csv(csv, 
                 dtype = {"genome": str}) # to keep the acc as string

# df ONLY with the genomes that are different in BLAST hits and IF2 hits
disc = df[df[f"BLAST_{min_length_tag}hits"] != df["IF2_hits"]] # discordant df
# Reduced discordant df (3 cols:)
df_disc_tocsv = disc[["genome", f"BLAST_{min_length_tag}hits", "IF2_hits"]]

disc_genomes = disc["genome"].tolist() # List of the discordant genomes

# Save discordant genomes into a csv
df_disc_tocsv.to_csv(f"{out_dir}/discordant.csv", index = False)

#### -------2) BLAST info about discordant genomes

blast_df = process_blast_tsv(tsv)  # To add strand, start and end
# To map genomes - contigs
mapping = contig_to_genome(genomes_dir)
contig2acc = {} # Dictionary to store mapping contig - acc
for contig, path in mapping.items(): # Iterates over contig ID and its path
    contig2acc[contig] = genome_key(path)

blast_df["genome"] = blast_df["seq_id"].map(contig2acc)

# Cols of the output of blast
cols = ["genome", "seq_id", "identity", "length", "query_start", 
        "query_end", "start", "end", "strand", "Evalue"]

# Keep only the rows whose genome is in the discordant list
sub_blast_df = blast_df[blast_df["genome"].isin(disc_genomes)] 
# Orders the df
sub_blast_df = sub_blast_df.sort_values(["genome", "seq_id", "start"])

## BLAST rows of the discordant genomes

sub_blast_df.to_csv(f"{out_dir}/discordant_blast.csv", index = False)

### --- 2.1 Control -> contigs not found in the mapping
# Contigs not found in the mapping have no genome (NaN)
n_total = len(blast_df) # Total BLAST rows
n_no_genome = blast_df["genome"].isna().sum() # Rows whose contig was not in the mapping
print(f"\n(control) >>>> BLAST rows without genome: {n_no_genome} of {n_total}.")

#### -------3) IF2 info about discordant genomes

info_df = pd.read_csv(if2_info, dtype = {"genome": str}) # to keep the acc as string

# Normalize the accession of each row with genome_key
normalized_genomes = []
for full_acc in info_df["genome"]:
    short_acc = genome_key(full_acc)
    normalized_genomes.append(short_acc)
info_df["genome"] = normalized_genomes

# Keep only the integrases (no CALIN) of the discordant genomes
if2_df = info_df[(info_df["genome"].isin(disc_genomes)) & (~info_df["calin"])] # NO CALIN
if2_df = if2_df[["genome", "locus_id", "start", "end", "strand", "integron_type", "integron_id"]]

## IF2 integrases of the discordant genomes
if2_df.to_csv(f"{out_dir}/discordant_IF2.csv", index = False)

##################################

calin_df = info_df[info_df["calin"]]      
no_calin = info_df[~info_df["calin"]]     

n_total_IF2 = len(info_df)                                   
n_calin = int(info_df["calin"].sum())                        
no_calin = info_df[~info_df["calin"]]                        
n_no_calin = len(no_calin)
n_complete = int((no_calin["integron_type"] == "complete").sum())
n_in0 = int((no_calin["integron_type"] == "In0").sum())

# BLAST hits (only the rows whose contig is in the mapping)
n_blast = int(blast_df["genome"].notna().sum())

print("\n=== Summary (number of hits) ===")
print(f"IF2 total (with CALIN):        {n_total_IF2}")
print(f"IF2 CALIN:                     {n_calin}")
print(f"IF2 without CALIN:             {n_no_calin}")
print(f"   - complete:                 {n_complete}")
print(f"   - In0:                      {n_in0}")
print(f"BLAST hits:                    {n_blast}")

# Same comparison at genome level
print("\n=== Summary (number of genomes) ===")
print(f"Genomes with IF2 (with CALIN): {info_df['genome'].nunique()}")
print(f"Genomes with CALIN:            {info_df[info_df['calin']]['genome'].nunique()}")
print(f"Genomes with IF2 w/o CALIN:    {no_calin['genome'].nunique()}")
print(f"Genomes with BLAST hits:       {int((df[f'BLAST_{min_length_tag}hits'] > 0).sum())}")

# Per-genome table
total_counts = info_df.groupby("genome").size()    # integrons per genome
calin_counts = calin_df.groupby("genome").size()   # CALIN per genome

rows = []
for genome in df["genome"]:   # all the genomes analyzed
    if genome in total_counts.index:
        n_total = int(total_counts[genome])
    else:
        n_total = 0

    if genome in calin_counts.index:
        n_cal = int(calin_counts[genome])
    else:
        n_cal = 0

    n_blast_genome = int(df.loc[df["genome"] == genome, f"BLAST_{min_length_tag}hits"].iloc[0])

    rows.append({"genome": genome,
                    "IF2_total": n_total,
                    "IF2_CALIN": n_cal,
                    "IF2_no_CALIN": n_total - n_cal,
                    f"BLAST_{min_length_tag}hits": n_blast_genome})

per_genome = pd.DataFrame(rows)

# Discordant genomes
per_genome_discordant = per_genome[per_genome[f"BLAST_{min_length_tag}hits"] != per_genome["IF2_no_CALIN"]]
per_genome_discordant.to_csv(f"{out_dir}/CALIN_vs_IF2_vs_BLAST.csv", index = False)